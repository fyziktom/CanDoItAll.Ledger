using System.Diagnostics;
using System.Security.Cryptography.X509Certificates;

string? originalDcpPath = ResolveOriginalDcpPath();

if (originalDcpPath is null)
{
    Console.Error.WriteLine("Could not find the Aspire DCP executable in the NuGet package cache.");
    return 1;
}

List<string> forwardedArguments = [.. args];
TryAddLocalTlsInspectionCa(forwardedArguments);

using Process process = new()
{
    StartInfo = new ProcessStartInfo(originalDcpPath)
    {
        RedirectStandardError = true,
        RedirectStandardOutput = true,
        UseShellExecute = false,
        WorkingDirectory = Environment.CurrentDirectory
    }
};

foreach (string argument in forwardedArguments)
{
    process.StartInfo.ArgumentList.Add(argument);
}

Console.CancelKeyPress += (_, eventArgs) =>
{
    eventArgs.Cancel = true;
    TryStopProcessTree(process);
};

process.Start();
Task outputTask = process.StandardOutput.BaseStream.CopyToAsync(Console.OpenStandardOutput());
Task errorTask = process.StandardError.BaseStream.CopyToAsync(Console.OpenStandardError());

await process.WaitForExitAsync();
await Task.WhenAll(outputTask, errorTask);

return process.ExitCode;

static void TryAddLocalTlsInspectionCa(List<string> forwardedArguments)
{
    if (forwardedArguments.Count == 0
        || !string.Equals(forwardedArguments[0], "start-apiserver", StringComparison.Ordinal)
        || forwardedArguments.Contains("--tls-ca-file", StringComparer.Ordinal)
        || !forwardedArguments.Contains("--tls-cert-thumbprint", StringComparer.Ordinal))
    {
        return;
    }

    string? configuredCaFile = Environment.GetEnvironmentVariable("CANDOITALL_DCP_PROXY_TLS_CA_FILE");

    if (!string.IsNullOrWhiteSpace(configuredCaFile) && File.Exists(configuredCaFile))
    {
        forwardedArguments.Add("--tls-ca-file");
        forwardedArguments.Add(configuredCaFile);
        return;
    }

    string? avgRootFile = TryExportAvgTlsInspectionRoot();

    if (avgRootFile is null)
    {
        return;
    }

    forwardedArguments.Add("--tls-ca-file");
    forwardedArguments.Add(avgRootFile);
}

static string? ResolveOriginalDcpPath()
{
    string? configuredPath = Environment.GetEnvironmentVariable("CANDOITALL_ORIGINAL_DCP_PATH");

    if (!string.IsNullOrWhiteSpace(configuredPath) && File.Exists(configuredPath))
    {
        return configuredPath;
    }

    string packagesRoot = Path.Combine(
        Environment.GetFolderPath(Environment.SpecialFolder.UserProfile),
        ".nuget",
        "packages",
        "aspire.hosting.orchestration.win-x64");

    if (!Directory.Exists(packagesRoot))
    {
        return null;
    }

    return Directory.EnumerateDirectories(packagesRoot)
        .Select(directory => new
        {
            Version = Version.TryParse(Path.GetFileName(directory), out Version? version) ? version : new Version(0, 0),
            DcpPath = Path.Combine(directory, "tools", OperatingSystem.IsWindows() ? "dcp.exe" : "dcp")
        })
        .Where(candidate => File.Exists(candidate.DcpPath))
        .OrderByDescending(candidate => candidate.Version)
        .Select(candidate => candidate.DcpPath)
        .FirstOrDefault();
}

static string? TryExportAvgTlsInspectionRoot()
{
    bool avgTlsInspectionDetected = Environment.GetEnvironmentVariable("SSLKEYLOGFILE")?
        .Contains("avgMonFltProxy", StringComparison.OrdinalIgnoreCase) == true;

    if (!avgTlsInspectionDetected)
    {
        return null;
    }

    try
    {
        using X509Store store = new(StoreName.Root, StoreLocation.CurrentUser);
        store.Open(OpenFlags.ReadOnly);

        X509Certificate2? certificate = store.Certificates
            .Find(
                X509FindType.FindBySubjectDistinguishedName,
                "CN=AVG Web/Mail Shield Root, O=AVG Web/Mail Shield, OU=generated by AVG Antivirus for SSL/TLS scanning",
                validOnly: false)
            .OfType<X509Certificate2>()
            .OrderByDescending(candidate => candidate.NotAfter)
            .FirstOrDefault();

        if (certificate is null)
        {
            return null;
        }

        string directory = Path.Combine(Path.GetTempPath(), "candoitall-economy-dcp-proxy");
        Directory.CreateDirectory(directory);

        string path = Path.Combine(directory, "avg-root.pem");
        File.WriteAllText(path, ExportCertificatePem(certificate));

        return path;
    }
    catch (UnauthorizedAccessException)
    {
        return null;
    }
    catch (IOException)
    {
        return null;
    }
}

static string ExportCertificatePem(X509Certificate2 certificate)
{
    string base64 = Convert.ToBase64String(certificate.RawData, Base64FormattingOptions.InsertLineBreaks);
    return $"-----BEGIN CERTIFICATE-----{Environment.NewLine}{base64}{Environment.NewLine}-----END CERTIFICATE-----{Environment.NewLine}";
}

static void TryStopProcessTree(Process process)
{
    try
    {
        if (!process.HasExited)
        {
            process.Kill(entireProcessTree: true);
        }
    }
    catch (InvalidOperationException)
    {
    }
}
